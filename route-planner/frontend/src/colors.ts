/**
 * Цвета маршрутов.
 *
 * Инженеров под два десятка, и различать их нужно на карте одним взглядом,
 * поэтому палитра подобрана по тону, а не сгенерирована из хеша: соседние
 * оттенки разведены.
 *
 * Цвет работает в двух местах сразу, и требования у них противоположные:
 *
 * * **линия на карте** — светлая подложка OSM, поэтому серые и мутные тона
 *   сливаются с дорогами. Спасает не темнота, а насыщенность: тёмная обводка
 *   под линией уже даёт контраст с фоном, а «дорожным» цвет делает именно
 *   отсутствие тона;
 * * **аватарка инженера** в списках — цвет идёт фоном, а инициалы поверх него
 *   почти чёрные (`--accent-ink`). Тёмный цвет делает их нечитаемыми.
 *
 * Первая версия палитры проваливала оба требования: `#a9a9a9` на карте
 * выглядел дорогой, а на `#000075` инициалы были не видны совсем. Поэтому все
 * тона держатся в середине по светлоте и высоко по насыщенности: ни серых, ни
 * почти чёрных, ни выцветших пастельных.
 *
 * Первые четырнадцать разведены сильнее всего — столько инженеров и выходит в
 * поле в обычный день. Дальше идут светлые варианты тех же тонов.
 */

const PALETTE = [
  '#f03e3e', '#37b24d', '#4c6ef5', '#e8590c', '#be4bdb',
  '#1098ad', '#f06595', '#74b816', '#f59f00', '#0ca678',
  '#845ef7', '#d6336c', '#339af0', '#20c997', '#da77f2',
  '#22b8cf', '#ff922b', '#51cf66', '#9775fa', '#94d82d',
]

const cache = new Map<string, string>()

export function engineerColor(id: string): string {
  const known = cache.get(id)
  if (known) return known
  // ENG-07 -> 7: порядковый номер даёт стабильный цвет между перезапусками
  const n = Number(id.replace(/\D/g, '')) || cache.size
  const color = PALETTE[(n - 1 + PALETTE.length) % PALETTE.length]
  cache.set(id, color)
  return color
}

