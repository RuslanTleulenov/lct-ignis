def export_pdf(pptx: Path) -> Path | None:
    """PDF через установленный PowerPoint. Без него — только pptx."""
    try:
        import win32com.client
    except ImportError:
        print("  pywin32 не установлен — PDF пропущен")
        return None
    pdf = pptx.with_suffix(".pdf")
    app = None
    try:
        app = win32com.client.Dispatch("PowerPoint.Application")
        deck = app.Presentations.Open(str(pptx), WithWindow=False)
        deck.SaveAs(str(pdf), 32)          # 32 = ppSaveAsPDF
        deck.Close()
        return pdf
    except Exception as exc:                # PowerPoint может быть не установлен
        print(f"  PDF не собрался: {exc}")
        return None
    finally:
        if app is not None:
            try:
                app.Quit()
            except Exception:
                pass


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--pdf", action="store_true", help="дополнительно собрать PDF")
    p.add_argument("--out", default=str(OUT))
    args = p.parse_args()
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")

    if not TEMPLATE.exists():
        raise SystemExit(f"Нет шаблона: {TEMPLATE}")
    missing = [n for n in ("overview.png", "engineer.png", "job.png")
               if not (ASSETS / n).exists()]
    if missing:
        raise SystemExit(f"Нет скриншотов: {', '.join(missing)} в {ASSETS}")

    prs = Presentation(str(TEMPLATE))
    order = build(prs)
    keep_and_order(prs, order)
    out = Path(args.out)
    prs.save(str(out))
    print(f"Собрано: {out}  ({len(order)} слайдов)")

    if args.pdf:
        pdf = export_pdf(out)
        if pdf:
            print(f"PDF:      {pdf}")


if __name__ == "__main__":
    main()
