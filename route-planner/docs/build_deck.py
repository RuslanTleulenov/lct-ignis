def put(shape, text: str, size_pt: float | None = None) -> None:
    """Вписать текст, сохранив оформление шаблона.

    Откуда брать свойства — не очевидно, и на этом легко потерять вёрстку.
    У заполненных надписей шаблона оформление лежит в первом прогоне
    (`a:rPr`), у пустых — в `a:endParaRPr`, «каким будет следующий набранный
    символ». Берём первое, что нашли: простое присваивание текста создаёт
    прогон без свойств, и слайд уезжает в шрифт и цвет по умолчанию — на
    белом фоне текст выходит почти невидимым.
    """
    tf = shape.text_frame
    first = tf.paragraphs[0]
    props = None
    if first.runs:
        found = first.runs[0]._r.find(qn("a:rPr"))
        if found is not None:
            props = copy.deepcopy(found)
    if props is None:
        found = first._p.find(qn("a:endParaRPr"))
        if found is not None:
            props = copy.deepcopy(found)
            props.tag = qn("a:rPr")

    lines = str(text).split("\n")
    tf.text = lines[0]
    for line in lines[1:]:
        tf.add_paragraph().text = line

    for para in tf.paragraphs:
        for run in para.runs:
            if props is not None:
                existing = run._r.find(qn("a:rPr"))
                if existing is not None:
                    run._r.remove(existing)
                run._r.insert(0, copy.deepcopy(props))
            if size_pt is not None:
                run.font.size = Pt(size_pt)


def picture(slide, shape, image: Path, fill_box: bool = False) -> None:
    """Поставить картинку на место образца, сохранив пропорции.

    `insert_picture` у место-заполнителя не годится: он переписывает элемент,
    и заданная в слайде позиция теряется — картинка уезжает в координаты из
    макета. Поэтому образец удаляем, а снимок ставим сами: вписываем в его
    прямоугольник по центру (`fill_box=True` — растянуть на всю рамку, для
    логотипов и подложек это не нужно).

    Фигура передаётся объектом, а не номером: удаление сдвигает нумерацию, и
    следующие обращения по индексу попали бы не в ту надпись.
    """
    box = (shape.left, shape.top, shape.width, shape.height)
    shape._element.getparent().remove(shape._element)
    left, top, width, height = box
    if not fill_box:
        with Image.open(image) as im:
            ratio = im.width / im.height
        if width / height > ratio:                 # рамка шире картинки
            new_width = int(height * ratio)
            left += (width - new_width) // 2
            width = new_width
        else:
            new_height = int(width / ratio)
            top += (height - new_height) // 2
            height = new_height
    slide.shapes.add_picture(str(image), left, top, width, height)


#: Ширина одного знака заголовка на плашке, дюймы. Снято с отрендеренного
#: слайда: «ЧТО ДЕЛАЕТ СЕРВИС» занимает 2,45 дюйма.
TITLE_CHAR_IN = 0.144
TITLE_PAD_IN = 0.65


def set_title(slide, badge, holder, text: str) -> None:
    """Заголовок слайда вместе с плашкой под ним.

    Плашка в шаблоне фиксированной ширины, а заголовок белый. Текст длиннее
    плашки уезжает на светлый фон и становится невидимым — поэтому плашку
    растягиваем под длину строки. Логотипы организаторов начинаются с 7,5
    дюйма, дальше заезжать нельзя.
    """
    put(holder, text)
    if badge is None:
        return
    width = min(Inches(TITLE_PAD_IN + TITLE_CHAR_IN * len(text)), Inches(6.9))
    if width > badge.width:
        badge.width = width


def chart_effect(slide, shape) -> None:
    """Заменить демонстрационную диаграмму шаблона сравнением по факту.

    В образце лежит кольцевая диаграмма с выдуманными долями. Доли здесь не
    при чём: сравниваются три варианта одного и того же дня, поэтому ставим
    горизонтальные столбцы — их читают слева направо без легенды.
    """
    box = (shape.left, shape.top, shape.width, shape.height)
    shape._element.getparent().remove(shape._element)

    data = CategoryChartData()
    data.categories = ["Базовый вариант ТЗ", "Факт диспетчера", "Сервис"]
    data.add_series("Заявок закрыто в срок", (52, 63, 66))
    frame = slide.shapes.add_chart(XL_CHART_TYPE.BAR_CLUSTERED, *box, data)
    chart = frame.chart
    chart.has_legend = False
    chart.has_title = False

    plot = chart.plots[0]
    plot.has_data_labels = True
    plot.gap_width = 60
    labels = plot.data_labels
    labels.font.size = Pt(18)
    labels.font.bold = True
    labels.font.color.rgb = RGBColor(0x1C, 0x1D, 0x22)
    labels.position = XL_LABEL_POSITION.OUTSIDE_END

    series = plot.series[0]
    series.format.fill.solid()
    series.format.fill.fore_color.rgb = RGBColor(0xFF, 0x00, 0x53)

    axis = chart.category_axis
    axis.tick_labels.font.size = Pt(14)
    axis.has_major_gridlines = False
    value_axis = chart.value_axis
    value_axis.visible = False
    value_axis.has_major_gridlines = False


def keep_and_order(prs: Presentation, order: list[int]) -> None:
    """Оставить в колоде только нужные слайды шаблона, в заданном порядке.

    `order` — номера слайдов исходного шаблона, с единицы.
    """
    sldIdLst = prs.slides._sldIdLst
    ids = list(sldIdLst)
    keep = [ids[n - 1] for n in order]
    for element in ids:
        sldIdLst.remove(element)
    for element in keep:
        sldIdLst.append(element)


